pub fn arabic_base_letters(character: char) -> Option<&'static str> {
    if !('\u{FB50}'..='\u{FEFF}').contains(&character) {
        return None;
    }
    let code = character as u32;
    RUNS.iter().find_map(|&(start, letters)| letters.split('|').nth(code.checked_sub(start)? as usize))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn folds_presentation_forms_to_base_letters() {
        let folded: String = "\u{FEE3}\u{FEAE}\u{FEA3}\u{FE92}\u{FE8E}"
            .chars()
            .map(|character| arabic_base_letters(character).unwrap())
            .collect();
        assert_eq!(folded, "مرحبا");
        assert_eq!(arabic_base_letters('\u{FEFC}'), Some("لا"));
        assert_eq!(arabic_base_letters('\u{FB56}'), Some("پ"));
        assert_eq!(arabic_base_letters('\u{FDF2}'), Some("الله"));
        assert_eq!(arabic_base_letters('\u{FDFA}'), Some("صلى الله عليه وسلم"));
        assert_eq!(arabic_base_letters('\u{FE70}'), Some("\u{064B}"));
        assert_eq!(arabic_base_letters('\u{FE75}'), None);
        assert_eq!(arabic_base_letters('م'), None);
        assert_eq!(arabic_base_letters('a'), None);
    }
}
